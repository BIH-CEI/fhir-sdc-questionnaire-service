#!/usr/bin/env bash
# Regenerate the committed TEST-ONLY PKI in deploy/mtls/test-pki/.
#
# The output is committed on purpose: CI and local runs use the same
# certificates and the same hard-coded allowlist. The CA private key is
# discarded at the end, so no further certificates can be issued under this
# CA. nginx refuses to start with this CA when MTLS_ENV=production
# (see 10-forbid-test-pki.sh).
#
#   site-a  signed by the test CA, on the allowlist      -> 200
#   site-b  signed by the test CA, NOT on the allowlist  -> 403
#   rogue   signed by a different CA                     -> rejected in TLS
#
# Usage: deploy/mtls/make-test-pki.sh   (overwrites test-pki/)

set -euo pipefail

OUT="$(cd "$(dirname "$0")" && pwd)/test-pki"
DAYS=3650
MARK="TEST ONLY - NOT FOR PRODUCTION"
mkdir -p "$OUT"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

key() { openssl genrsa -out "$1" 2048 2>/dev/null; }

# Test CA (key stays in $tmp and is deleted on exit)
key "$tmp/ca.key"
openssl req -x509 -new -key "$tmp/ca.key" -sha256 -days "$DAYS" \
    -subj "/O=$MARK/CN=FHIR-SDC Test CA" \
    -addext "basicConstraints=critical,CA:true" \
    -addext "keyUsage=critical,keyCertSign,cRLSign" \
    -out "$OUT/ca.pem"

issue() {  # $1 name, $2 CA cert, $3 CA key, $4 extensions
    key "$OUT/$1.key"
    openssl req -new -key "$OUT/$1.key" -subj "/O=$MARK/CN=$1" -out "$tmp/$1.csr"
    printf '%b' "$4" > "$tmp/$1.ext"
    openssl x509 -req -in "$tmp/$1.csr" -CA "$2" -CAkey "$3" -CAcreateserial \
        -days "$DAYS" -sha256 -extfile "$tmp/$1.ext" -out "$OUT/$1.pem" 2>/dev/null
}

issue server "$OUT/ca.pem" "$tmp/ca.key" \
    "basicConstraints=CA:false\nkeyUsage=critical,digitalSignature,keyEncipherment\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:localhost,DNS:mtls-proxy,IP:127.0.0.1\n"
for site in site-a site-b; do
    issue "$site" "$OUT/ca.pem" "$tmp/ca.key" \
        "basicConstraints=CA:false\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n"
done

# Foreign CA for the rogue client (not trusted by nginx)
key "$tmp/rogue-ca.key"
openssl req -x509 -new -key "$tmp/rogue-ca.key" -sha256 -days "$DAYS" \
    -subj "/O=$MARK/CN=Rogue CA" -addext "basicConstraints=critical,CA:true" -out "$tmp/rogue-ca.pem"
issue rogue "$tmp/rogue-ca.pem" "$tmp/rogue-ca.key" \
    "basicConstraints=CA:false\nkeyUsage=critical,digitalSignature\nextendedKeyUsage=clientAuth\n"

# Allowlist: nginx's $ssl_client_fingerprint is the SHA-1 of the certificate,
# lowercase hex without colons. Format: "<fingerprint> <site>;"
fp=$(openssl x509 -in "$OUT/site-a.pem" -noout -fingerprint -sha1 | cut -d= -f2 | tr -d : | tr 'A-F' 'a-f')
cat > "$OUT/allowlist.map" <<EOF
# TEST ONLY - generated by make-test-pki.sh. Forbidden when MTLS_ENV=production.
$fp site-a;
EOF

# Reference for the production guard (10-forbid-test-pki.sh): the test CA's
# base64 body, kept outside test-pki/ so it is mounted in every stack.
grep -v -- '-----' "$OUT/ca.pem" | tr -d '\n' > "$OUT/../forbidden-test-ca.b64"

rm -f "$OUT/ca.srl"
chmod 644 "$OUT"/*.key  # nginx and curl in containers read them as non-owner; test keys only
echo "Wrote $OUT (site-a fingerprint $fp)"
